from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class CitationSchema(BaseModel):
    # Core Phase 6 Provenance Fields
    id: str = Field(..., description="Unique citation identifier")
    document_id: str = Field(..., description="Source document ID")
    chunk_id: str = Field(..., description="Source chunk ID")
    chunk_index: int = Field(default=0, description="0-based chunk sequence index")
    source_filename: str = Field(..., description="Original source document filename")
    page_start: Optional[int] = Field(default=None, description="1-based start page (null if unavailable/TXT)")
    page_end: Optional[int] = Field(default=None, description="1-based end page (null if unavailable/TXT)")
    passage: str = Field(..., description="Exact retrieved chunk passage text")
    distance: float = Field(..., description="ChromaDB cosine distance (lower is better, [0, 2])")
    similarity_score: float = Field(..., description="Cosine similarity score (higher is better, [0, 1])")

    # Frontend Compatibility Fields
    docId: str = Field(..., description="Alias for document_id")
    docName: str = Field(..., description="Alias for source_filename")
    pageNumber: Optional[int] = Field(default=None, description="Representative page number")
    chunkId: str = Field(..., description="Alias for chunk_id")
    similarityScore: float = Field(..., description="Alias for similarity_score")
    sectionTitle: str = Field(default="Source Reference", description="Section or provenance label")
    highlightCoordinates: Optional[Dict[str, float]] = None


class ChatMessageSchema(BaseModel):
    role: str = Field(..., description="'user' or 'assistant'")
    content: str
    timestamp: Optional[str] = None


class ChatMessageResponse(BaseModel):
    message_id: str
    session_id: str
    role: str
    content: str
    citations: List[CitationSchema] = Field(default_factory=list)
    created_at: str


class ChatRequest(BaseModel):
    message: Optional[str] = Field(default=None, description="User query or instruction")
    query: Optional[str] = Field(default=None, description="Alternative alias for message")
    session_id: Optional[str] = Field(default=None, description="Existing session ID to append conversation turn")
    document_ids: Optional[List[str]] = Field(default=None, description="Active scoped document IDs for retrieval")
    top_k: Optional[int] = Field(default=5, ge=1, le=20, description="Number of context passages to retrieve (1-20)")
    retrieval_mode: str = Field(default="dense", description="'dense', 'hybrid', or 'bm25'")
    history: Optional[List[ChatMessageSchema]] = Field(default=None, description="Optional caller-supplied history override")

    @property
    def effective_query(self) -> str:
        q = (self.message or self.query or "").strip()
        return q


class ChatResponse(BaseModel):
    id: str = Field(..., description="Assistant message identifier")
    session_id: str = Field(..., description="Chat session ID")
    role: str = "assistant"
    answer: str = Field(..., description="Grounded answer generated by LLM")
    content: str = Field(..., description="Alias for answer for UI rendering")
    timestamp: str = Field(..., description="Formatted timestamp")
    citations: List[CitationSchema] = Field(default_factory=list, description="Verified citations linked to retrieved chunks")
    retrieved_chunks: List[Dict[str, Any]] = Field(default_factory=list, description="Raw chunk metadata from ChromaDB")
    provider: str = Field(..., description="LLM provider name ('groq', 'mock')")
    model: str = Field(..., description="LLM model identifier")
    retrieval_metadata: Dict[str, Any] = Field(default_factory=dict, description="Retrieval latency and count metrics")
    generation_metadata: Dict[str, Any] = Field(default_factory=dict, description="LLM generation tokens and latency metrics")
    confidence_score: float = Field(default=0.94, description="Average similarity metric of cited chunks")
    latency_ms: float = Field(default=0.0, description="End-to-end processing latency in ms")
    tokens_processed: int = Field(default=0, description="Total tokens processed in query and generation")
    retrieval_mode: str = Field(default="dense", description="Retrieval mode used")


class ChatSessionSummary(BaseModel):
    session_id: str
    title: str
    created_at: str
    updated_at: str
    message_count: int


class ChatSessionDetail(BaseModel):
    session_id: str
    title: str
    created_at: str
    updated_at: str
    messages: List[ChatMessageResponse]
